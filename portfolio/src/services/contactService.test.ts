import { afterEach, expect, it, vi } from 'vitest'
import { createContactSubmitter, validateContact } from './contactService'
const payload = { name: 'Visiteur test', email: 'test@example.org', message: 'Un message de test, jamais envoyé à un service réel.' }
afterEach(() => { vi.useRealTimers() })

it('validates mandatory fields, email and maximum lengths centrally', () => {
  expect(Object.keys(validateContact({ name: ' ', email: '', message: ' ' }))).toEqual(['name', 'email', 'message'])
  expect(validateContact({ ...payload, email: 'invalid' }).email).toBeTruthy()
  expect(validateContact({ ...payload, email: 'test@example.org?bcc=other@example.org' }).email).toBeTruthy()
  expect(validateContact({ ...payload, name: 'x'.repeat(101) }).name).toBeTruthy()
  expect(validateContact({ ...payload, message: 'x'.repeat(5001) }).message).toBeTruthy()
  expect(validateContact(payload)).toEqual({})
})
it('never sends or claims success without a configured endpoint, on invalid data or a filled honeypot', async () => {
  const fetcher = vi.fn<typeof fetch>()
  const unavailable = await createContactSubmitter(undefined, fetcher)(payload)
  expect(unavailable.success).toBe(false)
  expect(fetcher).not.toHaveBeenCalled()
  expect((await createContactSubmitter('/api/contact', fetcher)({ ...payload, name: '' })).success).toBe(false)
  expect((await createContactSubmitter('/api/contact', fetcher)(payload, { website: 'bot' })).success).toBe(false)
  expect(fetcher).not.toHaveBeenCalled()
})
it('accepts only a successful HTTP response carrying an explicit boolean acknowledgement', async () => {
  const fetcher = vi.fn<typeof fetch>()
    .mockResolvedValueOnce(new Response(JSON.stringify({ success: true }), { status: 202 }))
    .mockResolvedValueOnce(new Response(JSON.stringify({ success: 'true' }), { status: 200 }))
    .mockResolvedValueOnce(new Response(JSON.stringify({}), { status: 200 }))
    .mockResolvedValueOnce(new Response(JSON.stringify({ success: true }), { status: 500 }))
  const submit = createContactSubmitter('/api/contact', fetcher)
  expect(await submit(payload)).toEqual({ success: true })
  expect((await submit(payload)).success).toBe(false)
  expect((await submit(payload)).success).toBe(false)
  expect((await submit(payload)).success).toBe(false)
  const request = fetcher.mock.calls[0][1]!
  expect(request.credentials).toBe('omit')
  expect(request.redirect).toBe('error')
  expect(JSON.parse(String(request.body))).toEqual({ ...payload, website: '' })
})
it('returns actionable errors for rate limits, malformed acknowledgements and network failures', async () => {
  const fetcher = vi.fn<typeof fetch>()
    .mockResolvedValueOnce(new Response('{}', { status: 429 }))
    .mockResolvedValueOnce(new Response('not json', { status: 200 }))
    .mockRejectedValueOnce(new TypeError('offline'))
  const submit = createContactSubmitter('/api/contact', fetcher)
  const limited = await submit(payload)
  expect(limited.success).toBe(false)
  if (!limited.success) expect(limited.error).toContain('Trop de tentatives')
  expect((await submit(payload)).success).toBe(false)
  expect((await submit(payload)).success).toBe(false)
})
it('bounds a stalled request and supports cancellation without reporting success', async () => {
  vi.useFakeTimers()
  const fetcher = vi.fn<typeof fetch>().mockImplementation((_url, options) => new Promise((_resolve, reject) => {
    options?.signal?.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')))
  }))
  const result = createContactSubmitter('/api/contact', fetcher)(payload)
  await vi.advanceTimersByTimeAsync(15001)
  expect(await result).toMatchObject({ success: false, code: 'timeout' })
  const controller = new AbortController(); controller.abort()
  expect(await createContactSubmitter('/api/contact', fetcher)(payload, { signal: controller.signal })).toMatchObject({ success: false, code: 'aborted' })
})
