import { describe, expect, it } from 'vitest'
import { featuredProjects, projectById, projects, secondaryProjects } from './projects'

describe('central project catalogue', () => {
  it('contains the four featured projects in order and the six secondary projects', () => {
    expect(featuredProjects.map(project => project.id)).toEqual(['noven', 'projecthub', 'lifehub', 'career-os'])
    expect(secondaryProjects.map(project => project.id)).toEqual(['l-animations', 'migration-aws', 'mtc-erp', 'booknest', 'playzone', 'nyumbart'])
    expect(projects).toHaveLength(10)
    expect(new Set(projects.map(project => project.id)).size).toBe(projects.length)
    expect(projects.every(project => project.title && project.category && project.status && project.summary)).toBe(true)
  })

  it('only exposes GitHub actions for repositories that are publicly reachable', () => {
    expect(projects.filter(project => project.githubPublic).map(project => project.id)).toEqual(['l-animations', 'booknest', 'nyumbart'])
    for (const project of projects) {
      if (project.links?.github) expect(typeof project.githubPublic).toBe('boolean')
      if (project.githubPublic) expect(project.links?.github).toMatch(/^https:\/\/github\.com\//)
    }
    expect(projects.find(project => project.id === 'projecthub')?.links).toBeUndefined()
    expect(projects.find(project => project.id === 'career-os')?.links).toBeUndefined()
    expect(projects.find(project => project.id === 'migration-aws')?.links).toBeUndefined()
  })

  it('keeps Noven as the featured lead with a complete, non-empty case study', () => {
    const noven = projectById.get('noven')
    expect(noven?.featured).toBe(true)
    expect(featuredProjects[0]?.id).toBe('noven')
    expect(noven?.featuredContent?.hook).toBeTruthy()
    expect(noven?.featuredContent?.role).toBeTruthy()
    expect(noven?.featuredContent?.technologies).toEqual(['TypeScript', 'Node.js', 'PostgreSQL', 'Redis'])
    expect(noven?.description).toBeTruthy()
    expect(noven?.problem).toBeTruthy()
    expect(noven?.solution).toBeTruthy()
    expect(noven?.features?.length).toBeGreaterThan(0)
    expect(noven?.architecture).toBeTruthy()
    expect(noven?.contribution).toBeTruthy()
    expect(noven?.challenges?.length).toBeGreaterThan(0)
    expect(noven?.achievements).toBeTruthy()
    expect(noven?.nextSteps?.length).toBeGreaterThan(0)
  })

  it('integrates ProjectHub as the second featured card with a complete case study', () => {
    const projecthub = projectById.get('projecthub')
    expect(featuredProjects[1]?.id).toBe('projecthub')
    expect(projecthub?.featured).toBe(true)
    expect(projecthub?.summary).toBeTruthy()
    expect(projecthub?.signature).toBe("D'une maquette à une application métier fonctionnelle.")
    expect(projecthub?.team).toBeTruthy()
    expect(projecthub?.featuredContent?.role).toBe('Développeur full-stack — conception et implémentation')
    expect(projecthub?.description).toBeTruthy()
    expect(projecthub?.problem).toBeTruthy()
    expect(projecthub?.solution).toBeTruthy()
    expect(projecthub?.features?.length).toBe(8)
    expect(projecthub?.architecture).toBeTruthy()
    expect(projecthub?.contribution).toContain('backend')
    expect(projecthub?.challenges?.length).toBe(3)
    expect(projecthub?.achievements).toContain('full-stack')
    expect(projecthub?.nextSteps).toBeUndefined()
    expect(projecthub?.links).toBeUndefined()
  })

  it('integrates LifeHub as the third featured card with a complete case study', () => {
    const lifehub = projectById.get('lifehub')
    expect(featuredProjects[2]?.id).toBe('lifehub')
    expect(lifehub?.featured).toBe(true)
    expect(lifehub?.summary).toBeTruthy()
    expect(lifehub?.signature).toBe('La bonne action, au bon moment.')
    expect(lifehub?.featuredContent?.role).toBe('Conception produit, architecture et développement full-stack')
    expect(lifehub?.description).toBeTruthy()
    expect(lifehub?.problem).toBeTruthy()
    expect(lifehub?.solution).toBeTruthy()
    expect(lifehub?.features?.length).toBe(7)
    expect(lifehub?.architecture).toBeTruthy()
    expect(lifehub?.contribution).toContain('full-stack')
    expect(lifehub?.challenges?.length).toBe(5)
    expect(lifehub?.achievements).toBeTruthy()
    expect(lifehub?.nextSteps?.length).toBe(5)
    expect(lifehub?.links?.github).toBe('https://github.com/Tranck04/lifehub-concours')
    expect(lifehub?.githubPublic).toBe(false)
  })

  it('integrates Career OS as the fourth featured card with a complete case study', () => {
    const careerOs = projectById.get('career-os')
    expect(featuredProjects[3]?.id).toBe('career-os')
    expect(careerOs?.featured).toBe(true)
    expect(careerOs?.summary).toBe('Transformer ses ambitions en trajectoires concrètes.')
    expect(careerOs?.signature).toBe('Transformer ses ambitions en trajectoires concrètes.')
    expect(careerOs?.featuredContent?.role).toBe('Conception produit, modélisation de domaine et développement')
    expect(careerOs?.description).toBeTruthy()
    expect(careerOs?.problem).toBeTruthy()
    expect(careerOs?.solution).toBeTruthy()
    expect(careerOs?.features?.length).toBe(6)
    expect(careerOs?.featuresSectionTitle).toBe('Le domaine étudié.')
    expect(careerOs?.architecture).toBeTruthy()
    expect(careerOs?.contribution).toBeTruthy()
    expect(careerOs?.challenges?.length).toBe(4)
    expect(careerOs?.achievements).toBeTruthy()
    expect(careerOs?.nextSteps?.length).toBe(5)
    expect(careerOs?.links).toBeUndefined()
  })

  it('does not fabricate case-study content for the other six projects', () => {
    for (const project of projects.filter(project => project.id !== 'noven' && project.id !== 'projecthub' && project.id !== 'lifehub' && project.id !== 'career-os')) {
      expect(project.description).toBeUndefined()
      expect(project.problem).toBeUndefined()
      expect(project.solution).toBeUndefined()
      expect(project.features).toBeUndefined()
      expect(project.architecture).toBeUndefined()
      expect(project.contribution).toBeUndefined()
      expect(project.challenges).toBeUndefined()
      expect(project.achievements).toBeUndefined()
      expect(project.nextSteps).toBeUndefined()
    }
  })
})
